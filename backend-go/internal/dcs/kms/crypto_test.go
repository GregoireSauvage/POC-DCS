// TestEmptyInputs validates edge cases
func TestEmptyInputs(t *testing.T) {
	pepper := []byte("pepper")

	// Empty string
	result1 := ComputeHMACLookup(pepper, "")
	if len(result1) != 32 {
		t.Errorf("Expected 32 bytes for empty string, got %d", len(result1))
	}

	// Should be deterministic even for empty
	result2 := ComputeHMACLookup(pepper, "")
	if !hmac.Equal(result1, result2) {
		t.Error("Empty string HMAC should be deterministic")
	}
}

