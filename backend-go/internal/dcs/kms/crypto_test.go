// TestNormalizeExternalID validates normalization matches Python: strip().upper()
func TestNormalizeExternalID(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected string
	}{
		{"simple lowercase", "abc123", "ABC123"},
		{"already uppercase", "ABC123", "ABC123"},
		{"leading whitespace", "  abc123", "ABC123"},
		{"trailing whitespace", "abc123  ", "ABC123"},
		{"both whitespace", "  abc123  ", "ABC123"},
		{"tabs and newlines", "\t\nabc123\n\t", "ABC123"},
		{"mixed case", "AbC123", "ABC123"},
		{"with spaces inside", "  abc 123  ", "ABC 123"},
		{"unicode", "  café  ", "CAFÉ"},
		{"empty string", "", ""},
		{"whitespace only", "   ", ""},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := NormalizeExternalID(tt.input)
			if result != tt.expected {
				t.Errorf("NormalizeExternalID(%q) = %q, want %q",
					tt.input, result, tt.expected)
			}
		})
	}
}

// TestComputeHMACLookup validates HMAC-SHA256 computation
func TestComputeHMACLookup(t *testing.T) {
	pepper := []byte("test-pepper-secret")
	value := "TEST123"

	result := ComputeHMACLookup(pepper, value)

	// Verify length (SHA256 = 32 bytes)
	if len(result) != 32 {
		t.Fatalf("expected 32-byte output, got %d", len(result))
	}

	// Verify correctness by recomputing with standard library
	h := hmac.New(sha256.New, pepper)
	h.Write([]byte(value))
	expected := h.Sum(nil)

	if !hmac.Equal(result, expected) {
		t.Errorf("HMAC mismatch: got %x, want %x", result, expected)
	}
}

// TestHMACDeterministic ensures same input produces same output
func TestHMACDeterministic(t *testing.T) {
	pepper := []byte("secret")
	value := "TEST"

	result1 := ComputeHMACLookup(pepper, value)
	result2 := ComputeHMACLookup(pepper, value)

	if !hmac.Equal(result1, result2) {
		t.Error("HMAC should be deterministic")
	}
}

// TestHMACUniqueness ensures different inputs produce different outputs
func TestHMACUniqueness(t *testing.T) {
	pepper := []byte("secret")

	result1 := ComputeHMACLookup(pepper, "VALUE1")
	result2 := ComputeHMACLookup(pepper, "VALUE2")

	if hmac.Equal(result1, result2) {
		t.Error("different inputs should produce different outputs")
	}
}

